// TEST-ONLY TOOL. Re-anchors the differential pins in lib/html/sanitize.pair.test.ts
// to the frozen 0ac6cfa reference running on the currently installed dependencies.
// Use it only when a dependency upgrade (sanitize-html, postcss, parse5) changes the
// sanitizer output and the pair test still reports no mismatches between the shipped
// sanitizer and the reference; see the header of that test for the full procedure.
//
//   bun lib/testFixtures/htmlSanitize/genGolden.ts [golden.json]
//
// Writes the golden file (default: the pinned fixture next to this script) and prints
// the fuzz stream hashes to paste into FUZZ_STREAM_HASHES.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { sanitizeHtmlForDisplay } from "./sanitizeReference0ac6cfa";
import { sanitizeDifferentialInputs } from "./sanitizeDifferentialInputs";
import { SANITIZE_FUZZ_CASES, SANITIZE_FUZZ_SEEDS, sanitizeFuzzInputs } from "./sanitizeFuzz";

const sha256 = (value: string) => createHash("sha256").update(value).digest("hex");
const version = (name: string) => JSON.parse(readFileSync(path.join("node_modules", name, "package.json"), "utf8")).version as string;
const output = process.argv[2] ?? path.join(import.meta.dir, "sanitizeGolden0ac6cfa.json");

// parse-srcset (inside sanitize-html) logs every invalid descriptor of the fuzz corpus.
const log = console.log;
console.log = () => {};

const entries = sanitizeDifferentialInputs().map(({ name, html }) => {
  const block = sanitizeHtmlForDisplay(html), allow = sanitizeHtmlForDisplay(html, "allow");
  return { name, input: sha256(html), block: sha256(block), allow: sha256(allow), remoteContentBanner: block !== allow };
});
const dependencies = ["sanitize-html", "postcss", "parse5"].map((name) => `${name} ${version(name)}`).join(", ");
writeFileSync(output, JSON.stringify({
  commit: "0ac6cfa",
  note: `SHA-256 of sanitizeHtmlForDisplay(input, 'block'|'allow') of the frozen 0ac6cfa reference (lib/testFixtures/htmlSanitize/sanitizeReference0ac6cfa.ts). remoteContentBanner = block !== allow (the reader's 'remote content blocked' banner). Regenerated by genGolden.ts with ${dependencies}.`,
  entries
}, null, 1) + "\n");

const streams = SANITIZE_FUZZ_SEEDS.map((seed) => {
  const stream = createHash("sha256");
  for (const input of sanitizeFuzzInputs(seed)) {
    stream.update(sanitizeHtmlForDisplay(input)).update("\0").update(sanitizeHtmlForDisplay(input, "allow")).update("\0");
  }
  return `  ${seed}: "${stream.digest("hex")}"`;
});
console.log = log;
console.log(`${entries.length} golden entries (${entries.filter((entry) => entry.remoteContentBanner).length} with banner) -> ${output}`);
console.log(`FUZZ_STREAM_HASHES (${SANITIZE_FUZZ_CASES} documents per seed, ${dependencies}):`);
console.log(streams.join(",\n"));
