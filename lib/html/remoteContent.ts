import type { UserAccountPrefs } from "../data";
import { extractPrimaryEmail } from "../senderIdentity";

export type RemoteContentMode = "block" | "allow";

export function remoteContentSenderKey(sender?: string | null) {
  // Shared with From/To parsing. Both preference reads and writes use this key.
  return extractPrimaryEmail(sender) ?? "";
}

export function senderAllowsRemoteContent(prefs: UserAccountPrefs, sender?: string | null) {
  const key = remoteContentSenderKey(sender);
  return !!key && prefs.remoteContent?.allowedSenders?.[key] === true;
}

// Only attachment paths generated by the application are local mail resources.
// Other relative URLs could resolve to an external sender's host or app routes.
export function isLocalMailResource(value: string) {
  const url = value.trim();
  return /^(?:cid:|data:image\/|blob:)/i.test(url) ||
    /^\/api\/accounts\/[^/?#\\]+\/messages\/[^/?#\\]+\/attachments\/[^/?#\\]+(?:\?[^#\\]*)?$/.test(url);
}

export function messageHtmlCsp(mode: RemoteContentMode = "block") {
  const remote = mode === "allow" ? " https: http:" : "";
  // Opt-in permits image resources only; sender CSS/fonts never load remotely.
  return `default-src 'none'; img-src 'self' data: cid: blob:${remote}; style-src 'unsafe-inline'; font-src 'self' data:; base-uri 'none'; form-action 'none'; frame-ancestors 'self'`;
}
